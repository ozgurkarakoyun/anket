def t(lang, key, **kwargs):
    """Translation helper. Falls back to Turkish then English."""
    val = T.get(lang, {}).get(key) or T['tr'].get(key) or T['en'].get(key) or key
    if kwargs and isinstance(val, str):
        try:
            return val.format(**kwargs)
        except (KeyError, IndexError):
            return val
    return val


